// Regenerates data/world.js from the compiled engine: node -> name, region, tier, biome, parent.
// Run: node tools/gen-world.js   (after copying a new engine/joetopia-engine.js)
const vm = require('vm'), fs = require('fs'), path = require('path');
const root = path.join(__dirname, '..'); const store = {};
const ctx = { console, localStorage: { getItem: k => k in store ? store[k] : null, setItem: (k, v) => store[k] = String(v), removeItem: k => delete store[k] } };
vm.createContext(ctx); vm.runInContext(fs.readFileSync(path.join(root, 'engine/joetopia-engine.js'), 'utf8'), ctx);
const api = ctx.JoetopiaKt.com.grokbot.joetopia.game.JoetopiaApi;
api.reset(1); api.debug('create', 'BOUNCER', 'Tester'); api.choose(0, ''); api.debug('rates', '0', '0'); api.debug('flowers', 'off', '');
const extra = ['intro', 'courtyard', 'throne', 'ziggurat', 'sanctum', 'alley', 'megavip', 'backstage',
  'crypt_stair', 'crypt_hall', 'crypt_ossuary', 'crypt_chapel', 'thaddeus_tomb', 'eden_gate', 'eden_garden', 'tree_knowledge', 'tree_life'];
const seen = {}, parent = {}, q = ['village']; const out = {};
function biome(n, kind) {
  if (/^d_[a-z]+$/.test(n) || ['neverland', 'docks', 'alley'].includes(n) || /_landmark$/.test(n)) return 'city';
  if (/_club$/.test(n) || /^(megarave|floor_|bar_|chill|creators|megavip|backstage|ziggurat|sanctum)/.test(n)) return 'club';
  if (['village', 'market'].includes(n)) return 'village';
  if (n === 'crossroads') return 'farm';
  if (['forest', 'shrine'].includes(n)) return 'forest';
  if (['cave', 'lake'].includes(n)) return 'cave';
  if (['rave', 'vip', 'dealer'].includes(n)) return 'cavern_club';
  if (n === 'castle_gate') return 'wilds';
  if (/^crypt_|^thaddeus_tomb$/.test(n)) return 'cave';
  if (/^eden_|^tree_(knowledge|life)$/.test(n)) return 'forest';
  if (['courtyard', 'throne'].includes(n)) return 'castle';
  return kind === 'city' ? 'interior_city' : 'interior';
}
while (q.length || extra.length) {
  if (!q.length) q.push(extra.shift());
  const n = q.shift(); if (seen[n]) continue; seen[n] = 1;
  api.debug('teleport', n, ''); const s = JSON.parse(api.scene()), st = JSON.parse(api.status());
  const name = s.title.split(' — ')[0].trim();
  const p = JSON.parse(api.probe());
  if (!parent[n] && n !== 'village') { const m = p.filter(c => c.kind === 'move' && seen[c.target]).pop(); if (m) parent[n] = m.target; }
  out[n] = { name, region: st.region, tier: st.tier, kind: st.regionKind, biome: biome(n, st.regionKind), parent: parent[n] || null };
  p.forEach(c => { if (c.kind === 'move' && c.target && !seen[c.target]) { if (!parent[c.target]) parent[c.target] = n; q.push(c.target); } });
}
const ids = Object.keys(out).sort();
const body = ids.map(k => '  ' + JSON.stringify(k) + ': ' + JSON.stringify(out[k])).join(',\n');
fs.writeFileSync(path.join(root, 'data/world.js'), '// GENERATED by tools/gen-world.js from the engine. Names/regions come from the Kotlin sources.\n// You may hand-edit "biome" (city, club, village, farm, forest, cave, cavern_club, wilds, castle, interior, interior_city).\nwindow.JOETOPIA_WORLD = {\n' + body + '\n};\n');
console.log(ids.length, 'nodes');
